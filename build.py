"""Build dist/index.html (single self-contained page) from src/. Run: python3 build.py"""
import re, base64, pathlib, os, sys, json
S = pathlib.Path(__file__).parent / 'src'
ROOT = pathlib.Path(__file__).parent
# settings come from .env (never committed); see .env.example
ENV_KEYS = ['FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN', 'FIREBASE_PROJECT_ID', 'FIREBASE_STORAGE_BUCKET',
            'FIREBASE_MESSAGING_SENDER_ID', 'FIREBASE_APP_ID', 'INVIGILATOR_EMAILS']
env = {}
if (ROOT / '.env').exists():
    for line in (ROOT / '.env').read_text().splitlines():
        if '=' in line and not line.lstrip().startswith('#'):
            k, v = line.split('=', 1); env[k.strip()] = v.strip().strip('"\'')
env.update({k: v for k, v in os.environ.items() if k in ENV_KEYS})
missing = [k for k in ENV_KEYS if not env.get(k)]
if missing: sys.exit('Missing settings: ' + ', '.join(missing) + '. Locally: copy .env.example to .env and fill it in. On GitHub: add them as repository secrets.')
fb_cfg = json.dumps({'apiKey': env['FIREBASE_API_KEY'], 'authDomain': env['FIREBASE_AUTH_DOMAIN'], 'projectId': env['FIREBASE_PROJECT_ID'],
                     'storageBucket': env['FIREBASE_STORAGE_BUCKET'], 'messagingSenderId': env['FIREBASE_MESSAGING_SENDER_ID'], 'appId': env['FIREBASE_APP_ID']})
emails = [e.strip().lower() for e in env['INVIGILATOR_EMAILS'].split(',') if e.strip()]
(ROOT / 'firestore.rules').write_text((ROOT / 'firestore.rules.template').read_text()
    .replace("rules_version = '2';\n", "rules_version = '2';\n// Generated by build.py from firestore.rules.template and .env. Edit the template, not this file.\n", 1)
    .replace('__INVIGILATOR_EMAILS__', json.dumps(emails)))
(ROOT / '.firebaserc').write_text(json.dumps({'projects': {'default': env['FIREBASE_PROJECT_ID']}}, indent=2) + '\n')
tok = (S / 'assets/tokens-light.css').read_text()
light = re.search(r':root \{.*?\n\}\n', tok, re.S).group(0)
dark = re.search(r':root\[data-theme="dark"\] \{(.*?)\n\}\n', tok, re.S).group(1)
tokens = (light + '@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){' + dark + '\n  color-scheme:dark;}}\n'
          ':root[data-theme="dark"]{' + dark + '\n  color-scheme:dark;}\n')
logo = 'data:image/svg+xml;base64,' + base64.b64encode((S / 'assets/sugarcare-logo.svg').read_bytes()).decode()
head = ('<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>SugarCARE Assessment</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n'
        '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
        '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400;500;600;700;800&display=swap">\n'
        + ''.join('<script src="https://www.gstatic.com/firebasejs/10.14.1/firebase-' + m + '-compat.js"></script>\n' for m in ('app', 'auth', 'firestore')))
js = (S / 'firebase.js').read_text().replace('__FIREBASE_CONFIG__', fb_cfg) + (S / 'app.js').read_text() + (S / 'questions_upload.js').read_text() + (S / 'admins.js').read_text().replace('__MAIN_EMAILS__', json.dumps(emails))
out = (head + '<style>\n' + tokens + (S / 'style.css').read_text() + '</style>\n'
       + (S / 'body.html').read_text().replace('__LOGO__', logo) + '<script>\n' + js + '</script>\n')
# Test-only: EMU_HOST=<ip> python3 build.py writes dist-lan/index.html, forced onto the Firebase emulator at that
# address (for phones on the same Wi-Fi). It never writes dist/, so it can't be deployed by accident.
emu_host = os.environ.get('EMU_HOST', '').strip()
if emu_host:
    if not re.fullmatch(r'[0-9.]+|localhost', emu_host): sys.exit('EMU_HOST must be an IP address')
    out = out.replace('<script src="https://www.gstatic.com', '<script>window.__EMU_HOST=' + json.dumps(emu_host) + ';</script>\n<script src="https://www.gstatic.com', 1)
    out_dir, name = 'dist-lan', 'dist-lan/index.html'
else:
    out_dir, name = 'dist', 'dist/index.html'
(pathlib.Path(__file__).parent / out_dir).mkdir(exist_ok=True)
(pathlib.Path(__file__).parent / name).write_text(out)
print(name, len(out), 'bytes' + (' (TEST BUILD: emulator at ' + emu_host + ')' if emu_host else ''))
